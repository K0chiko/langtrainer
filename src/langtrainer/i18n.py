def translate(lang: str, key: str, **values) -> str:
    text = STRINGS.get(lang, STRINGS[DEFAULT_LANG]).get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    return text.format(**values) if values else text


def translate_value(lang: str, prefix: str, value: str) -> str:
    """Translate a stored value such as a status or category; unknown values are shown as they are."""
    key = f"{prefix}.{value}"
    return translate(lang, key) if key in STRINGS[DEFAULT_LANG] else value


def pick_language(cookie: str | None, accept_language: str | None) -> str:
    if cookie in LANGUAGES:
        return cookie
    for part in (accept_language or "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in LANGUAGES:
            return code
    return DEFAULT_LANG
